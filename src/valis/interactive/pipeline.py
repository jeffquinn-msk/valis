def run_processor_on_thumbnail(processor_spec, thumb_array, src_f):
    """Backwards-compatible re-export (see ``processors``)."""
    return processors.run_processor_on_thumbnail(processor_spec, thumb_array, src_f)


def check_and_correct_orientation(
    moving_img: pyvips.Image,
    reference_img: pyvips.Image,
    downsample_size: int = 2048,
    margin_threshold: float = 0.05,
    moving_processor=None,
    reference_processor=None,
    moving_src_f: str = "",
    reference_src_f: str = "",
):
    """Find the best D4 orientation of ``moving_img`` against ``reference_img``
    and return ``(corrected_pyvips_image, OrientationMatch)``.

    If ``moving_processor`` / ``reference_processor`` are provided, the
    corresponding side is preprocessed with that valis ``ImageProcesser``
    before NCC scoring — this is what makes the check usable across stains.
    """
    max_useful = min(
        reference_img.width,
        reference_img.height,
        moving_img.width,
        moving_img.height,
    )
    effective_size = min(downsample_size, max_useful)
    if effective_size != downsample_size:
        print(
            f"[orientation] requested size {downsample_size} clamped to "
            f"{effective_size} (smaller input side)"
        )

    if reference_processor is not None:
        rgb = processors.pyvips_to_thumbnail_rgb_array(reference_img, effective_size)
        ref_thumb = processors.run_processor_on_thumbnail(
            reference_processor, rgb, reference_src_f
        )
    else:
        ref_thumb = processors.pyvips_to_thumbnail_array(reference_img, effective_size)
    if moving_processor is not None:
        rgb = processors.pyvips_to_thumbnail_rgb_array(moving_img, effective_size)
        mov_thumb = processors.run_processor_on_thumbnail(
            moving_processor, rgb, moving_src_f
        )
    else:
        mov_thumb = processors.pyvips_to_thumbnail_array(moving_img, effective_size)

    match = orientation_check.find_best_orientation(
        ref_thumb, mov_thumb, downsample_size=effective_size, use_gradient=True
    )

    print("\n=== Orientation check ===")
    print(f"  thumbnail size       : {effective_size}x{effective_size}")
    print(f"  best transform       : {match.name}")
    print(f"  correction needed    : {orientation_check.describe(match)}")
    print(f"  best NCC score       : {match.score:+.4f}")
    identity_score = match.scores["identity"]
    margin = match.score - identity_score
    print(f"  identity NCC score   : {identity_score:+.4f}  (margin: {margin:+.4f})")
    print("  all scores           :")
    for name, score in sorted(match.scores.items(), key=lambda kv: -kv[1]):
        marker = "  <-- chosen" if name == match.name else ""
        print(f"    {name:<14s} {score:+.4f}{marker}")
    inconclusive = (
        margin_threshold > 0
        and (match.k != 0 or match.mirror)
        and margin < margin_threshold
    )
    if inconclusive:
        print(
            f"  >> margin {margin:+.4f} below threshold {margin_threshold}; "
            "treating orientation check as inconclusive and using identity."
        )
        match = orientation_check.OrientationMatch(
            name="identity",
            k=0,
            mirror=False,
            score=identity_score,
            scores=match.scores,
        )
    elif match.k == 0 and not match.mirror:
        print("  >> images already correctly oriented; no pre-rotation applied.")
    else:
        print(
            f"  >> applying {orientation_check.describe(match)} to moving image "
            "before registration."
        )
    print("=========================\n")

    corrected = orientation_check.apply_d4_pyvips(moving_img, match.k, match.mirror)
    return corrected, match


