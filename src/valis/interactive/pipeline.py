def convert_16to8_bit(image: pyvips.Image, clamp=None):
    if clamp:
        image = (image > clamp).ifthenelse(clamp, image)
    else:
        clamp = 2**16
    tile_processed = ((image / clamp) * 255).cast("uchar")
    return tile_processed.colourspace("b-w")


def warp_new_slide(new_img, registrar, source_img, dst_img, bbox_xywh=None):
    src_slide_obj = registrar.get_slide(source_img)
    dst_slide_obj = registrar.get_slide(dst_img)
    return src_slide_obj.warp_img_from_to(new_img, to_slide_obj=dst_slide_obj)


def create_progress_callback():
    """Create a pyvips ``eval`` progress callback for writing the output file."""
    pbar = tqdm(total=100, desc="Writing OME-TIFF", unit="%")
    last_update = time.time()

    def eval_callback(image, progress):
        if (time.time() - last_update) > 0.25:
            pbar.n = progress.percent
            pbar.refresh()

    eval_callback.close = lambda: pbar.close()
    return eval_callback


def vips2bf_dtype(vips_format):
    np_dtype = slide_tools.VIPS_FORMAT_NUMPY_DTYPE[vips_format]
    return NUMPY_FORMAT_BF_DTYPE[str(np_dtype().dtype)]


def create_ome_metadata(
    width: int,
    height: int,
    protein_names: List[str],
    protein_ids: List[str],
    um_per_px: float,
    dtype: str = "uint16",
) -> str:
    """Create OME-XML metadata for single or multi-channel images."""
    num_channels = len(protein_names)
    if len(protein_ids) != num_channels:
        raise ValueError(
            f"Length of protein_names ({num_channels}) and protein_ids "
            f"({len(protein_ids)}) must match"
        )
    if num_channels == 0:
        raise ValueError("Must provide at least one protein name and ID")

    ome = OME()
    channels = [
        Channel(
            id=ChannelID(f"Channel:0:{c}"), name=protein_names[c], samples_per_pixel=1
        )
        for c in range(num_channels)
    ]
    tiff_data_blocks = [
        TiffData(first_z=0, first_c=c, first_t=0, ifd=c, plane_count=1)
        for c in range(num_channels)
    ]
    planes = [Plane(the_z=0, the_c=c, the_t=0) for c in range(num_channels)]

    pixels = Pixels(
        id=PixelsID("Pixels:0"),
        dimension_order="XYZCT",
        size_x=width,
        size_y=height,
        size_z=1,
        size_c=num_channels,
        size_t=1,
        type=dtype,
        big_endian=False,
        physical_size_x=um_per_px,
        physical_size_y=um_per_px,
        physical_size_x_unit=UnitsLength.MICROMETER,
        physical_size_y_unit=UnitsLength.MICROMETER,
        channels=channels,
        tiff_data_blocks=tiff_data_blocks,
        planes=planes,
    )

    if num_channels == 1:
        image_name = f"{protein_names[0]} ({protein_ids[0]})"
    else:
        image_name = f"Multichannel ({', '.join(protein_ids)})"

    image = Image(id=ImageID("Image:0"), name=image_name, pixels=pixels)
    ome.images.append(image)
    return ome.to_xml()


def write_ome_tiff(
    images: List[pyvips.Image],
    names: List[str],
    output_path,
    um_per_px: float,
    scale: float = 1.0,
):
    first_height = images[0].height
    first_width = images[0].width
    first_format = images[0].format
    for img in images:
        if img.width != first_width or img.height != first_height:
            raise ValueError(
                f"mismatched image size:"
                f" {first_width}x{first_height} vs {img.width}x{img.height}"
            )
        if img.format != first_format:
            raise ValueError(f"mismatched format: {first_format} vs {img.format}")
    if scale < 1.0:
        images = [im.resize(scale) for im in images]

    ome_xml = create_ome_metadata(
        width=images[0].width,
        height=images[0].height,
        protein_names=names,
        protein_ids=names,
        um_per_px=um_per_px / scale,
        dtype=vips2bf_dtype(images[0].format),
    )

    stacked = pyvips.Image.arrayjoin(images, across=1)
    stacked.set_type(pyvips.GValue.gstr_type, "image-description", ome_xml)
    stacked.set_type(pyvips.GValue.gint_type, "page-height", images[0].height)

    stacked.set_progress(True)
    stacked.signal_connect("eval", create_progress_callback())

    stacked.tiffsave(
        output_path,
        pyramid=True,
        subifd=True,
        tile=True,
        compression="jpeg",
        tile_height=256,
        tile_width=256,
        Q=100,
        bigtiff=True,
    )

    print(f"\nSuccessfully wrote: {output_path}")


