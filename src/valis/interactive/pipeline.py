"""The slow, full-registration alignment flow, extracted from
``scripts/align_two_images.py`` so both the CLI and the web app can call it.

The public entry point is :func:`run_alignment`. Lower-level helpers
(``convert_16to8_bit``, ``write_ome_tiff``, ``check_and_correct_orientation``,
...) are exposed for reuse and testing.
"""

import os
import shutil
import time
from pathlib import Path
from typing import Callable, List, Optional

import numpy as np
import pyvips
from tqdm import tqdm

from ome_types import OME
from ome_types._autogenerated.ome_2016_06 import (
    Channel,
    TiffData,
    Plane,
    Pixels,
    UnitsLength,
    Image,
)
from ome_types.model.simple_types import ChannelID, PixelsID, ImageID

from valis import registration, orientation_check, slide_tools
from valis.serial_rigid import TooFewMatchesError
from valis.interactive import processors

NUMPY_FORMAT_BF_DTYPE = {
    "uint8": "uint8",
    "int8": "int8",
    "uint16": "uint16",
    "int16": "int16",
    "uint32": "uint32",
    "int32": "int32",
    "float32": "float",
    "float64": "double",
}

# The sparse-hematoxylin fallback sweep. Each (pct, sigma) gives a different
# density / blob-size tradeoff; we try several before giving up.
SPARSE_SWEEP = [
    {"sparse_pct": 90.0, "sparse_blur_sigma": 1.5},
    {"sparse_pct": 85.0, "sparse_blur_sigma": 2.0},
    {"sparse_pct": 95.0, "sparse_blur_sigma": 1.0},
    {"sparse_pct": 80.0, "sparse_blur_sigma": 2.5},
    {"sparse_pct": 97.0, "sparse_blur_sigma": 1.5},
]


